"""Explicit, recoverable OSS cleanup; no transcript depends on retaining source bytes."""

from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

from .storage import Conflict


class CleanupRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")
    resource_ids: list[str] = Field(min_length=1, max_length=1000)
    category: Literal["audio", "outputs", "results", "all"] = "audio"
    confirmed: Literal[True]


def stopped(job, clock):
    return (
        job["state"] in {"completed", "failed", "dismissed"}
        and job.get("lease_until", 0) <= clock()
        and (
            not job.get("task_id")
            or job.get("remote_done")
            or job["state"] in {"completed", "dismissed"}
        )
    )


def cleanup(catalog, request):
    from .catalog import all_records

    service, records = catalog.service, catalog.records
    resources = catalog.raw_resources()
    selected = set(request.resource_ids)
    chosen = [r for r in resources if r["id"] in selected and not r.get("deleted")]
    if len(chosen) != len(selected):
        raise ValueError("部分资源已不存在，请刷新。")
    aids = {aid for r in chosen for aid in r.get("audio_ids", [])}
    jobs = {j["id"]: j for j in all_records(records, "job")}
    plans = []
    for aid in sorted(aids):
        # Read the revision BEFORE inspecting jobs. Every new job/attempt reserves this
        # row first; a concurrent reservation makes the eventual cleanup CAS fail.
        audio = records.get("audio", aid)
        if not audio:
            continue
        shared = [r for r in resources if r["id"] not in selected and aid in r.get("audio_ids", [])]
        if shared:
            raise Conflict("音频与其他资源共享（含归档资源）；请先处理共享关系，不能单独删除。")
        related = [j for j in jobs.values() if j["audio_id"] == aid]
        # Re-read jobs after the audio revision to close the reservation/scan race.
        related = [records.get("job", j["id"]) for j in related]
        for jid, attempt in audio.get("job_guards", {}).items():
            guarded = records.get("job", jid)
            if not guarded or guarded["attempt"] < attempt:
                raise Conflict("有尚未完成提交的任务，请先恢复该任务再清理。")
            if not stopped(guarded, service.clock):
                raise Conflict("有运行中或待确认的云端任务，请等待完成或先恢复处理。")
            if not any(j["id"] == jid for j in related):
                related.append(guarded)
        if any(not stopped(j, service.clock) for j in related):
            raise Conflict("有运行中或待确认的云端任务，请等待完成或先恢复处理。")
        pending = audio.get("cleanup")
        if pending and pending["category"] != request.category:
            raise Conflict("上次清理未完成，请先重试相同类型的清理。")
        if not pending:
            keys = set()
            if request.category in {"audio", "all"} and audio["state"] != "deleted":
                keys.add(audio["key"])
            if request.category in {"outputs", "results", "all"}:
                for job in related:
                    # Export keys are immutable and generated by Service.step. Include
                    # every historical revision, not just the currently displayed files.
                    for attempt in range(1, job["attempt"] + 1):
                        keys.update(
                            f"results/{job['id']}/exports/{attempt}/transcript.{fmt}"
                            for fmt in ("json", "txt", "srt", "vtt")
                        )
                    if request.category in {"results", "all"} and job.get("raw_key"):
                        keys.add(job["raw_key"])
            pending = {
                "category": request.category,
                "keys": sorted(keys),
                "job_ids": [j["id"] for j in related],
                "previous_state": audio["state"],
                "audio_bytes": audio["size"] if audio["key"] in keys else 0,
            }
        plans.append((audio, pending))

    service.artifacts.ensure_unversioned()
    deleted, released = 0, 0
    for audio, plan in plans:
        # Persist intent before touching OSS. If any step fails, the same request can
        # replay exact-key deletes and complete metadata updates safely.
        claimed = records.put(
            "audio", audio["id"], {**audio, "state": "deleting", "cleanup": plan}, audio["revision"]
        )
        try:
            for key in plan["keys"]:
                service.artifacts.delete(key)
            if plan["category"] in {"outputs", "results", "all"}:
                for jid in plan["job_ids"]:
                    job = records.get("job", jid)
                    job["outputs"] = {}
                    if plan["category"] in {"results", "all"}:
                        job.pop("raw_key", None)
                        job["results_deleted"] = True
                    service.save(job)
            claimed.update(
                state="deleted" if plan["category"] in {"audio", "all"} else plan["previous_state"],
                cleanup=None,
            )
            if claimed["state"] == "deleted":
                claimed["deleted_at"] = service.clock()
            records.put("audio", audio["id"], claimed, claimed["revision"])
        except Exception as exc:
            raise Conflict(
                "OSS 清理未完成；已删除的文件不会恢复。请重试相同操作以完成剩余清理。"
            ) from exc
        deleted += len(plan["keys"])
        released += plan["audio_bytes"]
    return {"deleted_keys": deleted, "audio_bytes": released, "resources": len(chosen)}
